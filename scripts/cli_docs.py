"""Rebuild the generated parts of the docs from DeeZy's own code.

    python scripts/cli_docs.py           # rewrite the pages that are out of date
    python scripts/cli_docs.py --check   # write nothing; exit 1 if a page is stale

Two kinds of block are generated:

- docs/cli: each command's --help, from the parsers. Help is rendered 80
  columns wide, whatever the terminal, so the pages don't depend on who ran
  the script. Every command in the parser tree must be on a page.
- docs/formats: each format's data rates and defaults, as `deezy bitrates`
  lists them with no config.

Each generated part sits between a BEGIN marker and the END marker below; the
rest of the page (title, notes, examples) is written by hand and kept. A CLI
page that doesn't exist yet is created with a title and the generated part.
"""

import argparse
from collections.abc import Iterator
import os
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs" / "cli"
FORMAT_DOCS = ROOT / "docs" / "formats"
COLUMNS = "80"
BEGIN = (
    "<!-- BEGIN generated by scripts/cli_docs.py: edit the parsers in "
    "deezy/cli, not this block -->"
)
RATES_BEGIN = (
    "<!-- BEGIN generated by scripts/cli_docs.py from 'deezy bitrates': edit "
    "deezy/dee/spec.py, not this block -->"
)
END = "<!-- END generated -->"

# page -> the commands whose help it shows, in order
PAGES: dict[str, tuple[tuple[str, ...], ...]] = {
    "top-level.md": ((),),
    "encode.md": (("encode",),),
    "encode-dd.md": (("encode", "dd"),),
    "encode-ddp.md": (("encode", "ddp"),),
    "encode-ddp-bluray.md": (("encode", "ddp-bluray"),),
    "encode-ddp-atmos.md": (("encode", "ddp-atmos"),),
    "encode-ac4.md": (("encode", "ac4"),),
    "encode-ac4-ims.md": (("encode", "ac4-ims"),),
    "encode-ac4-atmos.md": (("encode", "ac4-atmos"),),
    "encode-aac.md": (("encode", "aac"),),
    "encode-thd.md": (("encode", "thd"),),
    "encode-thd-atmos.md": (("encode", "thd-atmos"),),
    "encode-preset.md": (("encode", "preset"),),
    "find.md": (("find",),),
    "info.md": (("info",),),
    "measure.md": (("measure",),),
    "bitrates.md": (("bitrates",),),
    "tools.md": (("tools",),),
    "config.md": (
        ("config",),
        ("config", "generate"),
        ("config", "info"),
        ("config", "validate"),
        ("config", "list-presets"),
    ),
    "temp.md": (("temp",), ("temp", "clean"), ("temp", "info")),
}

# format page -> the formats whose data rates it lists (TrueHD has none)
RATE_PAGES: dict[str, tuple[str, ...]] = {
    "dd.md": ("dd",),
    "ddp.md": ("ddp",),
    "ddp-bluray.md": ("ddp-bluray",),
    "ddp-atmos.md": ("ddp-atmos",),
    "ac4.md": ("ac4",),
    "ac4-ims.md": ("ac4-ims",),
    "ac4-atmos.md": ("ac4-atmos",),
    "aac.md": ("aac",),
}


def _import_deezy() -> None:
    if str(ROOT) not in sys.path:
        sys.path.insert(0, str(ROOT))


def build_parser() -> argparse.ArgumentParser:
    """DeeZy's full parser tree, built the way `cli_parser` builds it."""
    _import_deezy()
    import deezy.cli as cli

    parser = cli.create_main_parser()
    subparsers = parser.add_subparsers(dest="sub_command")
    groups = cli.create_common_argument_groups()
    cli.create_encode_parsers(subparsers, groups)
    cli.create_other_parsers(subparsers, groups)
    return parser


def _children(parser: argparse.ArgumentParser) -> dict[str, argparse.ArgumentParser]:
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            return dict(action.choices)
    return {}


def commands(
    parser: argparse.ArgumentParser, path: tuple[str, ...] = ()
) -> Iterator[tuple[tuple[str, ...], argparse.ArgumentParser]]:
    """Every command in the tree, parents first."""
    yield path, parser
    for name, child in _children(parser).items():
        yield from commands(child, (*path, name))


def help_text(parser: argparse.ArgumentParser) -> str:
    old = os.environ.get("COLUMNS")
    os.environ["COLUMNS"] = COLUMNS
    try:
        text = parser.format_help()
    finally:
        if old is None:
            del os.environ["COLUMNS"]
        else:
            os.environ["COLUMNS"] = old
    return "\n".join(line.rstrip() for line in text.strip("\n").splitlines())


def rates_text(names: tuple[str, ...]) -> str:
    _import_deezy()
    from deezy.cli.bitrates import bitrate_lines

    return "\n".join(line.rstrip() for line in bitrate_lines(names))


def command_name(path: tuple[str, ...]) -> str:
    return " ".join(("deezy", *path))


def _code(text: str) -> list[str]:
    return ["", "```text {.scrollable-code-block}", text, "```"]


def help_block(paths: tuple[tuple[str, ...], ...], helps: dict) -> str:
    parts = [BEGIN]
    for index, path in enumerate(paths):
        if index:
            parts += ["", f"## {command_name(path)}"]
        parts += _code(helps[path])
    return "\n".join([*parts, "", END])


def rates_block(names: tuple[str, ...]) -> str:
    return "\n".join([RATES_BEGIN, *_code(rates_text(names)), "", END])


def render(name: str, current: str | None, begin: str, block: str, title: str) -> str:
    """The page with its generated part replaced (or a new page)."""
    if current is None:
        return f"# {title}\n\n{block}\n"
    text = current.replace("\r\n", "\n")
    start = text.find(begin)
    end = text.find(END, start)
    if start < 0 or end < start:
        raise SystemExit(f"{name}: no {begin!r} ... {END!r} markers")
    return text[:start] + block + text[end + len(END) :]


def _read(file: Path) -> str | None:
    return file.read_bytes().decode("utf-8") if file.exists() else None


def pages(parser: argparse.ArgumentParser) -> dict[Path, str]:
    """Each generated page's wanted text (newlines as '\\n')."""
    helps = {path: help_text(p) for path, p in commands(parser)}
    on_pages = {path for paths in PAGES.values() for path in paths}
    missing = sorted(command_name(path) for path in helps if path not in on_pages)
    unknown = sorted(command_name(path) for path in on_pages if path not in helps)
    if missing or unknown:
        raise SystemExit(
            f"PAGES is out of step with the parsers: not on a page {missing}, "
            f"not a command {unknown}"
        )
    wanted = {}
    for page, paths in PAGES.items():
        file = DOCS / page
        block = help_block(paths, helps)
        title = command_name(paths[0])
        wanted[file] = render(page, _read(file), BEGIN, block, title)
    for page, names in RATE_PAGES.items():
        file = FORMAT_DOCS / page
        current = _read(file)
        if current is None:
            raise SystemExit(f"docs/formats/{page} doesn't exist")
        wanted[file] = render(page, current, RATES_BEGIN, rates_block(names), "")
    return wanted


def _name(file: Path) -> str:
    return file.relative_to(ROOT).as_posix()


def stale_pages(parser: argparse.ArgumentParser | None = None) -> list[str]:
    """The pages whose text differs from what the code gives."""
    stale = []
    for file, text in pages(parser or build_parser()).items():
        current = _read(file)
        if current is None or current.replace("\r\n", "\n") != text:
            stale.append(_name(file))
    return stale


def write_pages(parser: argparse.ArgumentParser) -> list[str]:
    written = []
    for file, text in pages(parser).items():
        current = _read(file)
        newline = "\r\n" if current and "\r\n" in current else "\n"
        if current is not None and current.replace("\r\n", "\n") == text:
            continue
        file.write_bytes(text.replace("\n", newline).encode("utf-8"))
        written.append(_name(file))
    return written


def main(argv: list[str] | None = None) -> int:
    args = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    args.add_argument("--check", action="store_true", help="write nothing")
    check = args.parse_args(argv).check
    parser = build_parser()
    if check:
        stale = stale_pages(parser)
        for name in stale:
            print(f"out of date: {name}")
        return 1 if stale else 0
    for name in write_pages(parser):
        print(f"wrote {name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
